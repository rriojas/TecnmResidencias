def main():
    parser = argparse.ArgumentParser(description="Migrate Legacy DB to v2 3FN PostgreSQL 18 Schema")
    parser.add_argument("--dump-file", default=r"c:\Users\rrioj\source\repos\TecNM\ResidenciasTecNM\SISTEMARESIDENCIA\Legacy\schemaLegacy.sql", help="Path to legacy SQL dump")
    parser.add_argument("--output-sql", default=r"c:\Users\rrioj\source\repos\TecNM\ResidenciasTecNM\SISTEMARESIDENCIA\docs\database\seed_v2.sql", help="Output path for v2 seed SQL")
    args = parser.parse_args()

    migrator = LegacyMigrator(args.dump_file)
    if os.path.exists(args.dump_file):
        migrator.run_dump_parse(args.dump_file)
    else:
        print(f"[WARN] Dump file not found at {args.dump_file}. Generating structure seeds.")

